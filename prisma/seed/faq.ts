export async function seedFaq(db: PrismaClient): Promise<number> {
  const order = new Map<FaqCategory, number>();
  for (const item of FAQ) {
    assertLocalized(item.question, `${item.id} question`);
    assertLocalized(item.answer, `${item.id} answer`);
    const sortOrder = order.get(item.category) ?? 0;
    order.set(item.category, sortOrder + 1);
    const data = { category: item.category, question: item.question, answer: item.answer, sortOrder, published: true };
    await db.faqItem.upsert({ where: { id: item.id }, create: { id: item.id, ...data }, update: data });
  }
  return FAQ.length;
}
