/**
 * Writes public/photos/CREDITS.md and PHOTOS_NEEDED.md from the photo registry
 * (src/config/photos.ts), the manifests and the demo listings. Run after any photo change
 * (the photo scripts run it for you):
 *
 *   npx tsx scripts/photos/write-docs.ts
 */
import fs from "node:fs";
import path from "node:path";
import { PHOTO_SLOTS, type PhotoFile } from "../../src/config/photos";
import { ALL_LISTINGS, demoPhotoFolder, demoPhotoPath } from "../../prisma/seed/listings/all";
import { LISTING_MANIFEST, PUBLIC_DIR, readManifest, ROOT, SLOT_MANIFEST } from "./lib.mjs";

const slotFiles = readManifest(SLOT_MANIFEST) as Record<string, PhotoFile>;
const listingFiles = readManifest(LISTING_MANIFEST) as Record<string, PhotoFile>;
const cell = (text: string) => text.replace(/\|/g, "\\|");
const kb = (bytes: number) => `${Math.round(bytes / 1024)} KB`;

type Slot = (typeof PHOTO_SLOTS)[keyof typeof PHOTO_SLOTS] & { fallback?: string };

// ─── CREDITS.md ──────────────────────────────────────────────

const credits: string[] = [
  "# Photo credits",
  "",
  "Every photo in `public/photos/`, where it comes from and its license. Generated by",
  "`npx tsx scripts/photos/write-docs.ts` from `src/config/photos-manifest.json` and",
  "`prisma/seed/listings/photo-manifest.json` — edit the sources in `scripts/photos/`, not this file.",
  "",
  "- **Unsplash License** and **Pexels License**: free to use, no attribution required (we credit anyway).",
  "- **CC BY / CC BY-SA** (Wikimedia Commons): the author must be credited — the site does this on",
  "  `/photo-credits` (linked from the footer). CC BY-SA photos are shared under the same license.",
  "- No photo is AI-generated, none is an Unsplash+ (premium) photo, and none is hotlinked.",
  "",
  "## Site photos",
  "",
  "| File | Shows | Author | License | Source |",
  "|---|---|---|---|---|",
];
for (const [src, file] of Object.entries(slotFiles)) {
  const c = file.credit;
  credits.push(
    c
      ? `| \`${src}\` | ${cell(c.title)} | ${cell(c.author)} | [${c.license}](${c.licenseUrl}) | [link](${c.source}) |`
      : `| \`${src}\` | — | — | — | — |`,
  );
}
credits.push(
  "",
  "## Demo listing photos",
  "",
  "Stock interiors and exteriors from Unsplash (Unsplash License). They are not photos of the demo",
  "properties and are deleted from the database together with the demo listings (the files stay in",
  "the repo until `public/photos/listings/` is removed).",
  "",
  "| File | Source |",
  "|---|---|",
);
for (const [src, file] of Object.entries(listingFiles)) credits.push(`| \`${src}\` | ${file.credit?.source ?? "—"} |`);
fs.writeFileSync(path.join(PUBLIC_DIR, "photos", "CREDITS.md"), `${credits.join("\n")}\n`);

// ─── PHOTOS_NEEDED.md ────────────────────────────────────────

function status(slot: Slot): string {
  const file = slotFiles[slot.src];
  if (!file) return slot.fallback ? `**missing** — shows \`${slot.fallback}\` meanwhile` : "**missing** — shows the “photo coming soon” placeholder";
  const license = file.credit?.license ?? "?";
  if (/^CC|Public domain/.test(license)) return `Wikimedia Commons (${license})`;
  return `stock (${license})`;
}

const groups: { title: string; prefix: string; note?: string }[] = [
  { title: "Home hero slideshow", prefix: "hero." },
  { title: "City photos", prefix: "city.", note: "Also stored as `City.photoUrl` (admin → Content → Cities)." },
  { title: "Category tiles", prefix: "category." },
  { title: "“List your property” card", prefix: "cta." },
  {
    title: "Jewish life",
    prefix: "jewish.",
    note: "The synagogue photos come from Wikimedia Commons: run `bash scripts/fetch-wikimedia-photos.sh` in the Codespace terminal.",
  },
];

const needed: string[] = [
  "# Photos needed",
  "",
  "Every place on the site that should eventually show a **real photo** (taken by us or by a host,",
  "or licensed for us). Today most of them show a free stock photo, and a few show a styled",
  "“photo coming soon” placeholder. Generated by `npx tsx scripts/photos/write-docs.ts` from",
  "`src/config/photos.ts`.",
  "",
  "**How to replace a photo:** save a JPEG/WebP at least the minimum size, landscape unless noted,",
  "with no people as the main subject, no logos or watermarks. Then either put it at the path below",
  "and run `node scripts/photos/import-photo.mjs <your-file> <path> \"<author>\" \"<license>\"`, or send",
  "it to the developer. Photos are resized (hero 2400 px, others 1600 px), converted to WebP and",
  "stripped of metadata (GPS) automatically.",
  "",
];
for (const group of groups) {
  needed.push(`## ${group.title}`, "");
  if (group.note) needed.push(group.note, "");
  needed.push("| Path | What it should show | Aspect ratio | Minimum size | Where it appears | Now |", "|---|---|---|---|---|---|");
  for (const [key, def] of Object.entries(PHOTO_SLOTS) as [string, Slot][]) {
    if (!key.startsWith(group.prefix)) continue;
    needed.push(`| \`public${def.src}\` | ${cell(def.shows)} | ${cell(def.ratio)} | ${def.minSize} | ${cell(def.usedIn)} | ${status(def)} |`);
  }
  needed.push("");
}
needed.push(
  "## Demo listings",
  "",
  "The 20 demo listings use stock photos (4–6 each, cover first). They are labeled “Demo” and are",
  "removed before launch (`npm run demo:remove -- --yes`), so real photos are only needed if a demo",
  "listing is turned into a real one. Real listings get their photos from the owners (the wizard).",
  "",
  "| Folder | What it should show | Files (cover first) | Aspect ratio | Minimum size | Where it appears |",
  "|---|---|---|---|---|---|",
);
for (const seed of ALL_LISTINGS) {
  const files = seed.photos.map((key) => `\`${path.basename(demoPhotoPath(seed, key))}\``).join(", ");
  const size = seed.photos.reduce((sum, key) => sum + (listingFiles[demoPhotoPath(seed, key)]?.bytes ?? 0), 0);
  needed.push(
    `| \`public${demoPhotoFolder(seed)}/\` | ${cell(seed.text.en.title)} (${seed.status}) | ${files} (${kb(size)}) | 3:2 landscape | 1600×1067 | Listing cards, the listing page gallery, map popups |`,
  );
}
needed.push("");
fs.writeFileSync(path.join(ROOT, "PHOTOS_NEEDED.md"), needed.join("\n"));
console.log("Wrote public/photos/CREDITS.md and PHOTOS_NEEDED.md");
