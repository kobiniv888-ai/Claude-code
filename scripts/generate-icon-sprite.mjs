// Builds public/icons/sprite-<hash>.svg from the Lucide icons that server components draw,
// src/components/ds/sprite-icons.generated.ts with its URL and the icon names, and
// src/components/ds/sprite-symbols.generated.ts with the same symbols for the hidden sprite that
// each page's HTML carries (the icons then need no extra request before the first paint).
//
//   node scripts/generate-icon-sprite.mjs
//
// Why: a Lucide icon from lucide-react is a client component, so each one in a server component
// is sent twice (its full <svg> in the HTML, a component reference in the RSC data) and hydrates.
// A sprite icon is <svg class="bi …"><use href="/icons/sprite-….svg#name"/></svg>: ~110 bytes
// instead of ~450, two elements instead of 3–6, nothing to hydrate. The file name carries a hash
// of its content, so it can be cached for a year. Add a name below, run the script, commit both files.
