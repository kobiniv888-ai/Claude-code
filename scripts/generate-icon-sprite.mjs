const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const attrs = (props) =>
  Object.entries(props)
    .filter(([key]) => key !== "key")
    .map(([key, value]) => `${key}="${String(value).replace(/"/g, "&quot;")}"`)
    .join(" ");

const symbols = [];
for (const name of NAMES) {
  // Use Lucide's own file names (aliases such as "building-2" re-export another file).
  const mod = await import(`lucide-react/dist/esm/icons/${name}.mjs`);
  if (!mod.__iconData) throw new Error(`${name} is an alias in lucide-react: use the name of the file it re-exports`);
  const node = mod.__iconData.node;
  const body = node.map(([tag, props]) => `<${tag} ${attrs(props)}/>`).join("");
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${body}</symbol>`);
}
const svg = `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join("")}</svg>\n`;
const hash = createHash("sha256").update(svg).digest("hex").slice(0, 10);
const dir = path.join(root, "public", "icons");
for (const old of fs.readdirSync(dir).filter((f) => /^sprite-[0-9a-f]+\.svg$/.test(f))) fs.unlinkSync(path.join(dir, old));
fs.writeFileSync(path.join(dir, `sprite-${hash}.svg`), svg);

const ts = `// Generated by scripts/generate-icon-sprite.mjs — do not edit. Lucide icons (ISC license).
export const SPRITE_URL = "/icons/sprite-${hash}.svg";

export const SPRITE_ICON_NAMES = ${JSON.stringify(NAMES, null, 2).replace(/"/g, '"')} as const;

export type SpriteIconName = (typeof SPRITE_ICON_NAMES)[number];

/** Not in the page's hidden sprite: drawn from SPRITE_URL (see scripts/generate-icon-sprite.mjs). */
export const FILE_ONLY_ICON_NAMES: readonly SpriteIconName[] = ${JSON.stringify(FILE_ONLY)};
`;
fs.writeFileSync(path.join(root, "src", "components", "ds", "sprite-icons.generated.ts"), ts);

// The same symbols for the hidden sprite in each page's HTML (src/components/ds/icon-sprite.tsx),
// with an id prefix so they can't clash with other ids on the page.
for (const name of FILE_ONLY) if (!NAMES.includes(name)) throw new Error(`FILE_ONLY lists ${name}, which is not in NAMES`);
const inline = symbols
  .filter((_, index) => !FILE_ONLY.includes(NAMES[index]))
  .map((symbol) => symbol.replace('<symbol id="', '<symbol id="bi-'))
  .join("");
const inlineTs = `// Generated by scripts/generate-icon-sprite.mjs — do not edit. Lucide icons (ISC license).
// Written into each page's HTML by src/components/ds/icon-sprite.tsx (server rendering only).
export const SPRITE_SYMBOLS = ${JSON.stringify(inline)};
`;
fs.writeFileSync(path.join(root, "src", "components", "ds", "sprite-symbols.generated.ts"), inlineTs);
console.log(`public/icons/sprite-${hash}.svg: ${NAMES.length} icons, ${svg.length} bytes`);
